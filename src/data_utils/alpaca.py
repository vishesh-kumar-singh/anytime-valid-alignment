"""
Stanford Alpaca dataset loading.

The Stanford Alpaca dataset (tatsu-lab/alpaca) contains 52k
instruction-following demonstrations generated by text-davinci-003.
Each entry has: instruction, input (optional context), output.

Used for general-purpose alignment evaluation — complementing
the math-focused GSM8K/MATH500 benchmarks.
"""

from typing import List, Optional

from datasets import DownloadConfig, load_dataset


def load_alpaca(
    max_examples: Optional[int] = None,
) -> List[dict]:
    """Load the Stanford Alpaca dataset.

    Returns:
        List of dicts with keys: question, answer
        (question = instruction + input if present)
    """
    try:
        ds = load_dataset(
            "tatsu-lab/alpaca",
            split="train",
            download_config=DownloadConfig(local_files_only=True),
        )
    except Exception:
        ds = load_dataset("tatsu-lab/alpaca", split="train")

    examples = []
    for i, item in enumerate(ds):
        if max_examples is not None and i >= max_examples:
            break

        instruction = item["instruction"]
        inp = item.get("input", "").strip()
        # Combine instruction + input context when present
        if inp:
            question = f"{instruction}\n\nInput: {inp}"
        else:
            question = instruction

        examples.append({
            "question": question,
            "answer": item.get("output", ""),
        })

    return examples
